use crate::cloudinit::*;
use fleet_proto::args::{SshKeyAlgo, SshPublicKey, UserName};

fn ed25519(seed: u8, comment: &str) -> SshPublicKey {
    let mut blob = Vec::new();
    blob.extend(11u32.to_be_bytes());
    blob.extend(b"ssh-ed25519");
    blob.extend(32u32.to_be_bytes());
    blob.extend([seed; 32]);
    SshPublicKey::new(SshKeyAlgo::Ed25519, blob, comment.into()).unwrap()
}

const PRIVATE: &str = "-----BEGIN OPENSSH PRIVATE KEY-----\nb3BlbnNzaC1rZXktdjEAAAAA\n-----END OPENSSH PRIVATE KEY-----\n";

fn input() -> CloudInit {
    CloudInit {
        admin: UserName::new("ops").unwrap(),
        authorized_keys: vec![
            ed25519(1, "fleet-device-mac1"),
            ed25519(2, "fleet-recovery"),
        ],
        host_keys: vec![HostKey {
            private_openssh: PRIVATE.into(),
            public: ed25519(3, "host"),
        }],
        hostname: Some("web-1".into()),
    }
}

