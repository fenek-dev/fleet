#[test]
fn golden_output() {
    assert_eq!(render(&input()).unwrap(), GOLDEN);
}

#[test]
fn quoting_is_structure_safe() {
    assert_eq!(quote("a\"b\\c\nd"), "\"a\\\"b\\\\c\\nd\"");
    assert_eq!(quote("x\u{7f}\u{1b}y"), "\"x\\u007f\\u001by\"");
    assert_eq!(
        quote("key: value # not a comment"),
        "\"key: value # not a comment\""
    );
}

#[test]
fn rejects_bad_input() {
    let mut c = input();
    c.host_keys.clear();
    assert!(render(&c).is_err());
    let mut c = input();
    c.host_keys[0].private_openssh =
        "-----BEGIN OPENSSH PRIVATE KEY-----\nx\"\n-----END OPENSSH PRIVATE KEY-----\n".into();
    assert!(render(&c).is_err());
    let mut c = input();
    c.host_keys.push(c.host_keys[0].clone());
    assert!(render(&c).is_err());
    let mut c = input();
    c.hostname = Some("Web_1".into());
    assert!(render(&c).is_err());
    let mut c = input();
    c.admin = UserName::new("root").unwrap();
    assert!(render(&c).is_err());
    let mut c = input();
    c.authorized_keys.clear();
    assert!(render(&c).is_err());
}
